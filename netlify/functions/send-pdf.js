// netlify/functions/send-pdf.js
const { Resend } = require("resend");
const resend = new Resend(process.env.RESEND_API_KEY);

exports.handler = async (event) => {
  /* ──────────────────────────────────────────────────────────────
   * 1.  CORS + pre-flight
   * ──────────────────────────────────────────────────────────── */
  const CORS_HEADERS = {
    "Access-Control-Allow-Origin":  "*",
    "Access-Control-Allow-Headers": "Content-Type,x-api-key",
    "Access-Control-Allow-Methods": "OPTIONS,POST",
  };

  if (event.httpMethod === "OPTIONS") {
    return { statusCode: 200, headers: CORS_HEADERS, body: "" };
  }

  /* ──────────────────────────────────────────────────────────────
   * 2.  Auth header
   * ──────────────────────────────────────────────────────────── */
  if (event.headers["x-api-key"] !== process.env.FUNC_API_KEY) {
    return { statusCode: 401, headers: CORS_HEADERS, body: "Unauthorized" };
  }

  /* ──────────────────────────────────────────────────────────────
   * 3.  Parse payload
   * ──────────────────────────────────────────────────────────── */
  let payload;
  try {
    payload = JSON.parse(event.body);
  } catch {
    return { statusCode: 400, headers: CORS_HEADERS, body: "Invalid JSON payload" };
  }

  const { customer, pdfDataUri, quotePdf } = payload;
  const summaryUri = quotePdf || pdfDataUri; // front-end sends `quotePdf`

  if (!customer || !summaryUri) {
    return { statusCode: 400, headers: CORS_HEADERS, body: "Missing customer or study PDF" };
  }

  /* ──────────────────────────────────────────────────────────────
   * 4.  Build the PDF attachment from its data-URI
   * ──────────────────────────────────────────────────────────── */
  const summaryBase64 = summaryUri.split(",")[1];
  const attachments = [
    {
      filename: `${customer.name || "Unknown"} Study Design.pdf`,
      content:  Buffer.from(summaryBase64, "base64"),
    },
  ];

  /* ──────────────────────────────────────────────────────────────
   * 5.  Send the email via Resend
   *     MAIL_FROM must be on a domain verified in Resend.
   *     MAIL_TO may be a comma-separated list of recipients.
   * ──────────────────────────────────────────────────────────── */
  const recipients = (process.env.MAIL_TO || "neurophys2@gmail.com")
    .split(",")
    .map((s) => s.trim())
    .filter(Boolean);

  try {
    const { error } = await resend.emails.send({
      from:    process.env.MAIL_FROM || "Muriphys Studies <studies@muriphys.com>",
      to:      recipients,
      subject: `New Muriphys Study Design from ${customer.name || "Unknown"}`,
      text:    `Study design generated by ${customer.name || "Unknown"} <${customer.email || "no email"}>.`,
      attachments,
    });

    if (error) {
      console.error("Resend error:", error);
      return { statusCode: 502, headers: CORS_HEADERS, body: JSON.stringify({ error }) };
    }

    return {
      statusCode: 200,
      headers:    CORS_HEADERS,
      body:       JSON.stringify({ message: "Email sent" }),
    };
  } catch (err) {
    console.error("Resend exception:", err.message);
    return {
      statusCode: 500,
      headers:    CORS_HEADERS,
      body:       JSON.stringify({ error: err.message }),
    };
  }
};
